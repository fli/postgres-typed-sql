export async function findTypedSqlFiles(
  config: ResolvedPostgresTypedSqlConfig,
  suffixes: readonly string[]
): Promise<string[]> {
  const files = new Map<string, string>()
  async function walk(directory: string): Promise<void> {
    const entries = await readdir(directory, { withFileTypes: true })
    for (const entry of entries) {
      const entryPath = join(directory, entry.name)
      if (entry.isDirectory()) {
        if (!ignoredDiscoveryDirectories.has(entry.name) && !entry.name.startsWith('.')) {
          await walk(entryPath)
        }
      } else if (entry.isFile() && suffixes.some((suffix) => entry.name.endsWith(suffix))) {
        const canonical = await realpath(entryPath)
        if (!files.has(canonical)) {
          files.set(canonical, entryPath)
        }
      }
    }
  }

  const includeRoots = new Map<string, string>()
  for (const includeRoot of config.include) {
    const canonical = await realpath(includeRoot)
    if (!includeRoots.has(canonical)) {
      includeRoots.set(canonical, includeRoot)
    }
  }
  for (const includeRoot of includeRoots.values()) {
    await walk(includeRoot)
  }
  return [...files.values()]
}

function generatedOutputPath(sourcePath: string): string {
  return `${sourcePath.slice(0, -typedSqlSourceSuffix.length)}${typedSqlOutputSuffix}`
}

async function readTypedSqlConfigs(generatorConfig: ResolvedPostgresTypedSqlConfig): Promise<TypedSqlConfig[]> {
  const sourcePaths = (await findTypedSqlFiles(generatorConfig, [typedSqlSourceSuffix])).toSorted((left, right) =>
    relativePath(generatorConfig, left).localeCompare(relativePath(generatorConfig, right))
  )
  const configs: TypedSqlConfig[] = []

  for (const sourcePath of sourcePaths) {
    const bytes = readFileSync(sourcePath)
    const text = bytes.toString('utf8')
    configs.push({
      ...parseTypedSqlConfig({ sourcePath, content: text, config: generatorConfig }),
      sourceSha256: sha256(bytes),
    })
  }

  return configs
}

function parseTypedSqlConfig(input: {
  sourcePath: string
  content: string
  config: ResolvedPostgresTypedSqlConfig
}): TypedSqlConfig {
  const { sourcePath, content: text, config: generatorConfig } = input
  const sourceFile = relativePath(generatorConfig, sourcePath)
  const parsedSource = parseTypedSqlSource(text, sourceFile)
  let name = basename(sourceFile, typedSqlSourceSuffix).replace(/-([A-Za-z0-9])/gu, (_match, next: string) =>
    next.toUpperCase()
  )
  let access: TypedSqlAccess | undefined
  const nullableParameters: NullableParameterDeclaration[] = []
  const columns: SqlColumn[] = []
  let firstNameLocation: string | undefined
  let firstAccessLocation: string | undefined
  const firstColumnDirectiveByName = new Map<string, string>()
  const firstNullableDirectiveByName = new Map<string, string>()

  for (const directive of parsedSource.directives) {
    const location = `${sourceFile}:${directive.line}`
    const kind = directive.kind
    const bodyParts = /^(\S+)(?:\s+([\s\S]*))?$/u.exec(directive.body)
    const identifier = bodyParts?.[1]
    const rawPgType = bodyParts?.[2]?.trim()
    if (kind === 'name') {
      if (!identifier || rawPgType) {
        throw new Error(`${location}: @name requires exactly one TypeScript binding identifier.`)
      }
      if (firstNameLocation) {
        throw new Error(`${location}: duplicate @name; first declared at ${firstNameLocation}.`)
      }
      assertTypeScriptBindingIdentifier(identifier, `${location}: @name`)
      firstNameLocation = location
      name = identifier
      continue
    }

    if (kind === 'access') {
      if ((identifier !== 'read' && identifier !== 'write') || rawPgType) {
        throw new Error(`${location}: @access requires exactly read or write.`)
      }

      if (firstAccessLocation) {
        throw new Error(`${location}: duplicate @access; first declared at ${firstAccessLocation}.`)
      }
      firstAccessLocation = location
      access = identifier
      continue
    }

    if (kind !== 'nullable' && kind !== 'bindNull' && kind !== 'column') {
      throw new Error(`${location}: unsupported typed SQL directive @${kind}.`)
    }

    if (!identifier) {
      throw new Error(`${location}: @${kind} requires a name.`)
    }
    if (kind !== 'column' && (rawPgType || !/^[A-Za-z_][A-Za-z0-9_]*$/u.test(identifier))) {
      throw new Error(`${location}: @${kind} requires exactly one named-parameter identifier.`)
    }
    if (kind === 'column' && rawPgType?.endsWith('?')) {
      throw new Error(`${location}: @column does not support ?; PostgreSQL determines result nullability.`)
    }

    const firstDirectiveByName = kind !== 'column' ? firstNullableDirectiveByName : firstColumnDirectiveByName
    const firstLocation = firstDirectiveByName.get(identifier)
    if (firstLocation) {
      throw new Error(`${location}: duplicate @${kind} ${identifier}; first declared at ${firstLocation}.`)
    }
    firstDirectiveByName.set(identifier, location)

    if (kind !== 'column') {
      nullableParameters.push({
        kind,
        line: directive.line,
        name: identifier,
      })
    } else {
      columns.push({
        name: identifier,
        pgType: rawPgType,
      })
    }
  }

  assertTypeScriptBindingIdentifier(name, `${sourceFile}: typed SQL filename`)

  return {
    access,
    columns,
    name,
    nullableParameters,
    outputPath: generatedOutputPath(sourcePath),
    sourceFile,
    sourcePath,
    sourceSha256: sha256(text),
    sql: parsedSource.sql,
  }
}

function compileTypedSql(config: TypedSqlConfig, parameterNaming: PostgresTypedSqlPropertyNaming): CompiledTypedSql {
  const nullableByName = new Map(config.nullableParameters.map((parameter) => [parameter.name, parameter]))
  const compiled = compileNamedParameters(config.sql, config.sourceFile)
  const parameters = compiled.parameterNames.map((name): SqlParameter => {
    const nullable = nullableByName.get(name)
    return {
      name,
      ...(nullable ? { nullBinding: nullable } : {}),
      propertyName: propertyNameForNaming(name, parameterNaming),
    }
  })
  assertUniquePublicNames(
    parameters.map((parameter) => parameter.propertyName),
    'parameter property',
    config.sourceFile
  )

  const unusedParameters = config.nullableParameters.filter(
    (parameter) => !parameters.some((used) => used.name === parameter.name)
  )
  if (unusedParameters.length > 0) {
    const first = unusedParameters[0] as NullableParameterDeclaration
    throw new Error(
      `${config.sourceFile}:${first.line}: @${first.kind} parameter ${first.name} is not used by the SQL.`
    )
  }

  return {
    valueModel: postgresValueModel,
    access: config.access,
    columns: config.columns,
    name: config.name,
    outputPath: config.outputPath,
    parameters,
    sourceFile: config.sourceFile,
    sourcePath: config.sourcePath,
    sourceSha256: config.sourceSha256,
    sql: compiled.sql,
  }
}

interface GeneratedJsonTypeDeclaration {
  readonly fields: readonly Pick<ResolvedSqlField, 'nullable' | 'propertyName' | 'tsType' | 'typeIncludesNull'>[]
  readonly name: string
}

function propertyNameForNaming(name: string, naming: PostgresTypedSqlPropertyNaming): string {
  return naming === 'camelCase' ? camelCasePropertyName(name) : name
}

function validateJsonShapeNames(
  shape: TypedSqlPostgresIrJsonShape,
  naming: PostgresTypedSqlPropertyNaming,
  sourceFile: string,
  context: string
): void {
  switch (shape.kind) {
    case 'array':
      validateJsonShapeNames(shape.element, naming, sourceFile, `${context}[]`)
      break
    case 'object':
      for (const field of shape.fields) {
        validateJsonShapeNames(field.shape, naming, sourceFile, `${context}.${field.name}`)
      }
      assertUniquePublicNames(
        shape.fields.map((field) => propertyNameForNaming(field.name, naming)),
        `JSON field in ${context}`,
        sourceFile
      )
      break
    case 'union':
      for (const [index, alternative] of shape.alternatives.entries()) {
        validateJsonShapeNames(alternative, naming, sourceFile, `${context}<alternative ${index + 1}>`)
      }
  }
}

function isJsonTraversalBarrier(shape: TypedSqlPostgresIrJsonShape): boolean {
  return shape.kind === 'opaque' || (shape.kind === 'scalar' && postgresJsonValueMayBeStructured(shape))
}

function applyOpaqueJsonBarriersToAlternatives(
  shapes: readonly TypedSqlPostgresIrJsonShape[]
): readonly TypedSqlPostgresIrJsonShape[] {
  if (shapes.length === 0) {
    return shapes
  }
  const alternatives = shapes.flatMap(flattenJsonShapeAlternatives)
  if (alternatives.some(isJsonTraversalBarrier)) {
    return shapes.map((shape) => ({ kind: 'opaque', nullability: shape.nullability }))
  }

  const arrayElements = alternatives.flatMap((alternative) =>
    alternative.kind === 'array' ? [alternative.element] : []
  )
  const safeArrayElements = applyOpaqueJsonBarriersToAlternatives(arrayElements)
  let arrayIndex = 0

  const objectFields = new Map<string, TypedSqlPostgresIrJsonField[]>()
  for (const alternative of alternatives) {
    if (alternative.kind !== 'object') {
      continue
    }
    for (const field of alternative.fields) {
      const fields = objectFields.get(field.name) ?? []
      fields.push(field)
      objectFields.set(field.name, fields)
    }
  }
  const safeObjectFieldShapes = new Map(
    [...objectFields].map(([name, fields]) => [
      name,
      applyOpaqueJsonBarriersToAlternatives(fields.map((field) => field.shape)),
    ])
  )
  const objectFieldIndexes = new Map<string, number>()

  const rewrite = (shape: TypedSqlPostgresIrJsonShape): TypedSqlPostgresIrJsonShape => {
    switch (shape.kind) {
      case 'array': {
        const element = safeArrayElements[arrayIndex]
        arrayIndex += 1
        return { ...shape, element: element ?? shape.element }
      }
      case 'object':
        return {
          ...shape,
          fields: shape.fields.map((field) => {
            const fieldIndex = objectFieldIndexes.get(field.name) ?? 0
            objectFieldIndexes.set(field.name, fieldIndex + 1)
            return {
              ...field,
              shape: safeObjectFieldShapes.get(field.name)?.[fieldIndex] ?? field.shape,
            }
          }),
        }
      case 'union':
        return { ...shape, alternatives: shape.alternatives.map(rewrite) }
      case 'opaque':
      case 'null':
      case 'sqlNull':
      case 'jsonScalar':
      case 'jsonNumber':
      case 'scalar':
      case 'stringLiteral':
        return shape
    }
  }

  return shapes.map(rewrite)
}

function applyOpaqueJsonBarriers(shape: TypedSqlPostgresIrJsonShape): TypedSqlPostgresIrJsonShape {
  return applyOpaqueJsonBarriersToAlternatives([shape])[0] ?? shape
}

function assertUniquePublicNames(names: readonly string[], kind: string, sourceFile: string): void {
  const firstIndexByName = new Map<string, number>()
  for (const [index, name] of names.entries()) {
    const firstIndex = firstIndexByName.get(name)
    if (firstIndex !== undefined) {
      throw new Error(
        `${sourceFile}: duplicate ${kind} name ${JSON.stringify(name)} at positions ${firstIndex + 1} and ${index + 1}.`
      )
    }
    firstIndexByName.set(name, index)
  }
}

function reserveGeneratedTypeBinding(
  bindings: Map<string, string>,
  name: string,
  source: string,
  sourceFile: string
): void {
  assertTypeScriptBindingIdentifier(name, `${sourceFile}: generated type for ${source}`)
  const firstSource = bindings.get(name)
  if (firstSource) {
    throw new Error(
      `${sourceFile}: generated TypeScript binding ${name} for ${source} collides with ${firstSource}. Alias the SQL field to give it a distinct name.`
    )
  }
  bindings.set(name, source)
}

function encodedTypeNameSegment(value: string): string {
  let encoded = ''
  for (const character of value) {
    encoded += /^[A-Za-z0-9_]$/u.test(character) ? character : `$${character.codePointAt(0)?.toString(16) ?? ''}$`
  }
  return `J${encoded.length}_${encoded}`
}

function scalarTsTypeForJsonShape(
  shape: Extract<TypedSqlPostgresIrJsonShape, { readonly kind: 'scalar' }>,
  dependencies: TypeScriptDependencies
): string {
  if (shape.checkConstraintType && postgresJsonSupportsStringLiteralRefinement(shape)) {
    return tsTypeForCheckConstraintType(shape.checkConstraintType)
  }

  const resolved = resolveTypeScriptJsonScalarTypeForPostgresType(shape)
  collectTypeResolutionDependencies(dependencies, resolved)
  return resolved.type
}

function jsonLiteralPrimitive(
  shape: TypedSqlPostgresIrJsonShape,
  rendered: string
): 'string' | 'number' | 'boolean' | undefined {
  if (shape.kind === 'stringLiteral' && rendered === quoteString(shape.value)) return 'string'
  if (shape.kind === 'scalar' && shape.checkConstraintType) {
    if (rendered === tsTypeForCheckConstraintType(shape.checkConstraintType)) return 'string'
  }
  if (shape.kind === 'jsonScalar') {
    if (typeof shape.value === 'string' && rendered === quoteString(shape.value)) return 'string'
    if (typeof shape.value === 'number' && rendered === String(shape.value)) return 'number'
    if (typeof shape.value === 'boolean' && rendered === String(shape.value)) return 'boolean'
  }
  return undefined
}

function tsTypeForJsonShape(
  shape: TypedSqlPostgresIrJsonShape,
  sourceFile: string,
  suggestedName: string,
  declarations: GeneratedJsonTypeDeclaration[],
  usedNames: Map<string, string>,
  dependencies: TypeScriptDependencies,
  naming: PostgresTypedSqlPropertyNaming
): string {
  function render(shape: TypedSqlPostgresIrJsonShape, name: string): string {
    switch (shape.kind) {
      case 'array':
        return `readonly (${render(shape.element, `${name}${encodedTypeNameSegment('element')}`)}${resultNullabilityAllowsNull(shape.element.nullability) && !jsonShapeIncludesNull(shape.element) ? ' | null' : ''})[]`
      case 'object':
        reserveGeneratedTypeBinding(usedNames, name, `JSON object ${name}`, sourceFile)
        declarations.push({
          fields: shape.fields.map((field) => ({
            nullable: resultNullabilityAllowsNull(field.shape.nullability) && !jsonShapeIncludesNull(field.shape),
            propertyName: propertyNameForNaming(field.name, naming),
            tsType: render(field.shape, `${name}${encodedTypeNameSegment(field.name)}`),
          })),
          name,
        })
        return name
      case 'opaque':
        dependencies.scalar.add('PgJsonValue')
        return 'PgJsonValue'
      case 'jsonNumber':
        dependencies.scalar.add('PgFiniteDecimal')
        return 'PgFiniteDecimal'
      case 'sqlNull':
        return 'null'
      case 'null':
      case 'jsonScalar':
        if (shape.kind === 'null') return 'null'
        if (typeof shape.value === 'string') return quoteString(shape.value)
        if (typeof shape.value === 'number') {
          dependencies.scalar.add('PgFiniteDecimal')
          return 'PgFiniteDecimal'
        }
        return String(shape.value)
      case 'union': {
        const alternatives = shape.alternatives.map((alternative, index) => {
          const type = render(alternative, `${name}${encodedTypeNameSegment(`alternative${index + 1}`)}`)
          return { type, literalPrimitive: jsonLiteralPrimitive(alternative, type) }
        })
        const renderedTypes = new Set(alternatives.map(({ type }) => type))
        // Codec type expressions are opaque. Only exact emitted primitives can
        // absorb our known literals; aliases and literal-only unions retain them.
        return [
          ...new Set(
            alternatives
              .filter(({ literalPrimitive }) => !literalPrimitive || !renderedTypes.has(literalPrimitive))
              .map(({ type }) => type)
          ),
        ].join(' | ')
      }
      case 'scalar':
        return scalarTsTypeForJsonShape(shape, dependencies)
      case 'stringLiteral': {
        if (postgresJsonSupportsStringLiteralRefinement(shape)) {
          return quoteString(shape.value)
        }
        const resolved = resolveTypeScriptJsonScalarTypeForPostgresType(shape)
        collectTypeResolutionDependencies(dependencies, resolved)
        return resolved.type
      }
    }
  }
  return render(shape, suggestedName)
}

function jsonShapeIncludesNull(shape: TypedSqlPostgresIrJsonShape): boolean {
  return (
    shape.kind === 'sqlNull' ||
    shape.kind === 'null' ||
    (shape.kind === 'union' && shape.alternatives.some((alternative) => jsonShapeIncludesNull(alternative)))
  )
}

function renderImports(config: ResolvedTypedSql, generatorConfig: ResolvedPostgresTypedSqlConfig): string {
  const lines: string[] = []
  if (config.scalarTypeImports.length > 0) {
    lines.push(
      `import type { ${config.scalarTypeImports.join(', ')} } from ${quoteString(generatorConfig.imports.scalars)}`
    )
  }
  lines.push(
    `import { createTypedSqlStatement, createTypedSqlExecutor } from ${quoteString(generatorConfig.imports.runtime)}`
  )

  return lines.join('\n')
}

function renderInterface(name: string, fields: GeneratedJsonTypeDeclaration['fields']): string {
  if (fields.length === 0) {
    return `export type ${name} = Record<string, never>`
  }

  return [
    `export interface ${name} {`,
    ...fields.map(
      (field) =>
        `  readonly ${quotePropertyName(field.propertyName)}: ${field.tsType}${field.nullable && !field.typeIncludesNull ? ' | null' : ''}`
    ),
    '}',
  ].join('\n')
}

function renderMetadata(
  entries: readonly (QueryDescriptor['columns'][number] | QueryDescriptor['parameters'][number])[]
): string {
  if (entries.length === 0) {
    return '[]'
  }

  const objects = entries.map((entry) => {
    const fields = [
      `name: ${quoteString(entry.name)}`,
      `nullable: ${entry.nullable}`,
      `pgType: ${quoteString(entry.pgType)}`,
      `pgTypeName: ${quoteString(entry.pgTypeName)}`,
      `pgTypeSchema: ${quoteString(entry.pgTypeSchema)}`,
      `propertyName: ${quoteString(entry.propertyName)}`,
      `type: ${JSON.stringify(entry.type)}`,
    ]
    if ('expressionSource' in entry) {
      fields.unshift(
        `expressionSource: ${JSON.stringify(entry.expressionSource)}`,
        ...(entry.jsonPlan ? [`jsonPlan: ${JSON.stringify(entry.jsonPlan)}`] : [])
      )
    }
    return `    {\n      ${fields.join(',\n      ')},\n    }`
  })
  return `[\n${objects.join(',\n')},\n  ]`
}

function queryDescriptor(config: ResolvedTypedSql): QueryDescriptor {
  const metadata = (field: ResolvedSqlField) => ({
    name: field.name,
    nullable: field.nullable,
    pgType: field.pgType,
    pgTypeName: field.pgTypeName,
    pgTypeSchema: field.pgTypeSchema,
    propertyName: field.propertyName,
    type: field.type,
  })
  return {
    valueModel: postgresValueModel,
    access: config.access,
    resultKind: config.resultKind,
    columns: config.columns.map((column) => ({
      expressionSource: column.expressionSource,
      ...(column.jsonPlan ? { jsonPlan: column.jsonPlan } : {}),
      ...metadata(column),
    })),
    command: config.command,
    name: config.name,
    parameterNames: config.parameters.map((parameter) => parameter.propertyName),
    parameters: config.parameters.map(metadata),
    resultRowMapping: 'positional',
    rowBounds: { min: config.rowBounds.min, max: config.rowBounds.max, proof: config.rowBounds.proof },
    text: config.sql,
  }
}

function renderStatement(config: ResolvedTypedSql): string {
  const descriptor = queryDescriptor(config)
  const paramsName = `${pascalCaseIdentifier(config.name)}Params`
  const rowName = `${pascalCaseIdentifier(config.name)}Row`
  const parameterNames = descriptor.parameterNames.map(quoteString).join(', ')
  const generatedTypeDeclarations =
    config.generatedTypeDeclarations.length > 0 ? `${config.generatedTypeDeclarations.join('\n\n')}\n\n` : ''

  return `${generatedTypeDeclarations}${renderInterface(paramsName, config.parameters)}

${renderInterface(rowName, config.columns)}

export const ${config.name} = createTypedSqlStatement<
  ${paramsName},
  ${rowName},
  ${quoteString(descriptor.access)},
  ${quoteString(descriptor.resultKind)}
>({
  valueModel: ${quoteString(descriptor.valueModel)},
  access: ${quoteString(descriptor.access)},
  columns: ${renderMetadata(descriptor.columns)},
  command: ${quoteString(descriptor.command)},
  resultKind: ${quoteString(descriptor.resultKind)},
  name: ${quoteString(descriptor.name)},
  parameterNames: [${parameterNames}],
  parameters: ${renderMetadata(descriptor.parameters)},
  rowBounds: { min: ${descriptor.rowBounds.min}, max: ${descriptor.rowBounds.max ?? 'null'}, proof: ${quoteString(descriptor.rowBounds.proof)} },
  text: ${quoteString(descriptor.text)},
})

export default createTypedSqlExecutor(${config.name})`
}

function renderTypedSql(config: ResolvedTypedSql, generatorConfig: ResolvedPostgresTypedSqlConfig): string {
  const sourcePath = renderTypeScriptLineCommentValue(`./${basename(config.sourcePath)}`)
  return `// ${generatedByMarker}
// Source: ${sourcePath}
// Value model: ${postgresValueModel}
// DO NOT EDIT MANUALLY

${renderImports(config, generatorConfig)}

${renderStatement(config)}
`
}

async function assertColumnAssertions(
  client: PostgresQueryable,
  config: CompiledTypedSql,
  resolvedColumns: readonly ResolvedSqlColumn[]
): Promise<void> {
  if (config.columns.length === 0) {
    return
  }

  const resolvedByName = new Map(resolvedColumns.map((column) => [column.name, column]))
  const typedAssertions: { readonly assertion: SqlColumn; readonly resolved: ResolvedSqlColumn }[] = []
  for (const assertion of config.columns) {
    const resolved = resolvedByName.get(assertion.name)
    if (!resolved) {
      throw new Error(`${config.sourceFile}: @column ${assertion.name} does not exist in the PostgreSQL result.`)
    }

    if (assertion.pgType) {
      typedAssertions.push({ assertion, resolved })
    }
  }

  if (typedAssertions.length === 0) {
    return
  }

  const result = await client.query<{ readonly oid: number | null; readonly ordinal: number }>(
    `
      select
        asserted.ordinality::int as ordinal,
        to_regtype(asserted.pg_type)::oid::int as oid
      from unnest($1::text[]) with ordinality as asserted(pg_type, ordinality)
    `,
    [typedAssertions.map(({ assertion }) => assertion.pgType)]
  )
  const oidByOrdinal = new Map(result.rows.map((row) => [row.ordinal, row.oid]))
  for (const [index, { assertion, resolved }] of typedAssertions.entries()) {
    const assertedOid = oidByOrdinal.get(index + 1)
    if (!assertedOid) {
      throw new Error(`${config.sourceFile}: unknown @column type ${assertion.pgType} for ${assertion.name}.`)
    }
    if (assertedOid !== resolved.pgTypeOid) {
      throw new Error(
        `${config.sourceFile}: result column ${assertion.name} type drift. Expected ${assertion.pgType}, PostgreSQL inferred ${resolved.pgType}.`
      )
    }
  }
}

async function resolveTypedSqlWithAnalyzer(
  configs: readonly CompiledTypedSql[],
  client: AnalysisDatabase,
  generatorConfig: ResolvedPostgresTypedSqlConfig
): Promise<ResolvedTypedSql[]> {
  const result = await buildTypedSqlPostgresIrFromCompiledConfigs(
    client,
    configs.map((config) => ({
      name: config.name,
      parameterNames: config.parameters.map((parameter) => parameter.name),
      sourceFile: config.sourceFile,
      sql: config.sql,
    }))
  )

  const resolvedQueries: ResolvedTypedSql[] = []
  if (result.queries.length !== configs.length) {
    throw new Error('PostgreSQL analyzer returned an incomplete statement result.')
  }
  for (const [index, ir] of result.queries.entries()) {
    const config = configs[index]
    if (!config) {
      throw new Error(`PostgreSQL analyzer returned an unexpected extra query ${ir.name}.`)
    }
    if (ir.name !== config.name || ir.sourceFile !== config.sourceFile) {
      throw new Error('PostgreSQL analyzer returned a mismatched statement identity.')
    }
    if (ir.postgresVersionNum !== client.postgresVersionNum) {
      throw new Error('PostgreSQL analyzer version disagrees with the analysis engine.')
    }

    const generatedDeclarations: GeneratedJsonTypeDeclaration[] = []
    const typeDependencies: TypeScriptDependencies = {
      ambient: new Set(),
      scalar: new Set(),
    }
    const statementTypeBindings: TypeScriptBinding[] = [
      { name: `${pascalCaseIdentifier(config.name)}Params`, source: 'parameter interface' },
      { name: `${pascalCaseIdentifier(config.name)}Row`, source: 'row interface' },
    ]
    assertUniqueTypeScriptBindings(statementTypeBindings, config.sourceFile)
    const usedGeneratedTypeNames = new Map(statementTypeBindings.map((binding) => [binding.name, binding.source]))
    const columns = ir.resultColumns.map((column, columnIndex): ResolvedSqlColumn => {
      const name = column.name ?? `column_${columnIndex + 1}`
      const propertyName = propertyNameForNaming(name, generatorConfig.naming.resultColumns)
      const suggestedJsonTypeName = `${pascalCaseIdentifier(config.name)}${encodedTypeNameSegment(name)}Json`
      const safeJsonShape = column.jsonShape
        ? safeJsonCodecShape(applyOpaqueJsonBarriers(column.jsonShape), generatorConfig.naming.structuredJsonFields)
        : undefined
      if (safeJsonShape) {
        validateJsonShapeNames(
          safeJsonShape,
          generatorConfig.naming.structuredJsonFields,
          config.sourceFile,
          `result column ${JSON.stringify(name)}`
        )
      }
      const jsonPlan = safeJsonShape
        ? jsonPlanForShape(safeJsonShape, generatorConfig.naming.structuredJsonFields)
        : undefined
      const jsonShape = safeJsonShape
      let tsType: string
      if (jsonShape) {
        typeDependencies.scalar.add('PgJson')
        tsType = `PgJson<${tsTypeForJsonShape(
          jsonShape,
          config.sourceFile,
          suggestedJsonTypeName,
          generatedDeclarations,
          usedGeneratedTypeNames,
          typeDependencies,
          generatorConfig.naming.structuredJsonFields
        )}>`
      } else {
        const arrayElement = column.arrayShape ? resolveBuiltinResultArrayElement(column) : undefined
        if (arrayElement && column.arrayShape) {
          collectTypeResolutionDependencies(typeDependencies, arrayElement)
          typeDependencies.scalar.add('PgArray')
          tsType = `PgArray<${arrayElement.type}${resultNullabilityAllowsNull(column.arrayShape.elementNullability) ? ' | null' : ''}>`
        } else if (column.checkConstraintType && postgresResultSupportsStringLiteralRefinement(column)) {
          tsType = tsTypeForCheckConstraintType(column.checkConstraintType)
        } else {
          const resolution = resolveTypeScriptResultTypeForPostgresType(column)
          collectTypeResolutionDependencies(typeDependencies, resolution)
          tsType = resolution.type
        }
      }
      return {
        expressionSource: column.expressionSource,
        ...(jsonPlan ? { jsonPlan } : {}),
        type: typeFact(column),
        name,
        nullable: resultNullabilityAllowsNull(column.nullability),
        pgType: column.pgType,
        pgTypeName: column.pgTypeName,
        pgTypeOid: column.pgTypeOid,
        pgTypeSchema: column.pgTypeSchema,
        propertyName,
        tsType,
      }
    })
    assertUniquePublicNames(
      columns.map((column) => column.propertyName),
      'result column',
      config.sourceFile
    )
    await assertColumnAssertions(client, config, columns)
    const parameterAnalysis: TypedSqlParameterAnalysis[] = []
    const parameters = config.parameters.map((parameter, paramIndex): ResolvedSqlField => {
      const analyzed = ir.params[paramIndex]
      if (!analyzed) {
        throw new Error(`${config.sourceFile}: analyzer returned no type for parameter ${parameter.name}.`)
      }

      const resolution =
        analyzed.checkConstraintType && postgresParameterSupportsStringLiteralRefinement(analyzed)
          ? {
              ambientBindings: [],
              scalarImports: [],
              type: tsTypeForCheckConstraintType(analyzed.checkConstraintType),
            }
          : resolveTypeScriptParameterTypeForPostgresType(analyzed)
      collectTypeResolutionDependencies(typeDependencies, resolution)
      if (parameter.nullBinding?.kind === 'nullable' && analyzed.nullAdmission !== 'accepts') {
        const reason =
          analyzed.nullAdmission === 'rejects'
            ? 'PostgreSQL proves that one of its uses rejects NULL'
            : 'PostgreSQL could not prove that every use accepts NULL'
        throw new Error(
          `${config.sourceFile}:${parameter.nullBinding?.line}: @nullable ${parameter.name} cannot be satisfied because ${reason}.`
        )
      }
      parameterAnalysis.push({
        name: parameter.name,
        propertyName: parameter.propertyName,
        nullBinding:
          parameter.nullBinding?.kind === 'nullable'
            ? 'provedNullable'
            : parameter.nullBinding?.kind === 'bindNull'
              ? 'callerNullable'
              : 'nonNull',
        nullAdmission: analyzed.nullAdmission,
      })
      return {
        name: parameter.name,
        nullable: parameter.nullBinding !== undefined,
        pgType: analyzed.pgType,
        pgTypeName: analyzed.pgTypeName,
        pgTypeSchema: analyzed.pgTypeSchema,
        propertyName: parameter.propertyName,
        tsType: resolution.type,
        type: typeFact(analyzed),
      }
    })
    const usesRecordUtilityType =
      parameters.length === 0 || columns.length === 0 || generatedDeclarations.some(({ fields }) => fields.length === 0)
    const ambientBindings = new Set(typeDependencies.ambient)
    if (usesRecordUtilityType) {
      ambientBindings.add('Record')
    }
    assertUniqueTypeScriptBindings(
      [
        { name: 'createTypedSqlStatement', source: 'generated runtime import' },
        { name: 'createTypedSqlExecutor', source: 'generated runtime import' },
        { name: config.name, source: 'exported statement constant' },
        ...[...usedGeneratedTypeNames].map(([name, source]) => ({ name, source })),
        ...[...ambientBindings].map((name) => ({ name, source: 'ambient TypeScript type' })),
        ...[...typeDependencies.scalar].map((name) => ({
          name,
          source: 'postgres-typed-sql scalar type import',
        })),
      ],
      config.sourceFile
    )

    const inferredAccess = typedSqlAccessFromEvidence(ir.accessEvidence)
    if (config.access === 'read' && inferredAccess === 'write') {
      const reasons =
        ir.accessEvidence.kind === 'notProvenReadOnly'
          ? ir.accessEvidence.reasons.map(accessConcernDescription).join('; ')
          : 'an unknown analyzer result'
      throw new Error(
        `${config.sourceFile}: @access read requires analyzer-proved read-only execution; PostgreSQL analysis found ${reasons}.`
      )
    }

    resolvedQueries.push({
      columns,
      access: config.access ?? inferredAccess,
      accessEvidence: publicAccessEvidence(ir.accessEvidence),
      parameterAnalysis,
      resultKind: ir.resultKind,
      command: typedSqlCommandFromPostgres(ir.command),
      generatedTypeDeclarations: generatedDeclarations.map(({ name, fields }) => renderInterface(name, fields)),
      typeExports: [
        ...generatedDeclarations.map(({ name }) => name),
        `${pascalCaseIdentifier(config.name)}Params`,
        `${pascalCaseIdentifier(config.name)}Row`,
      ],
      name: config.name,
      outputPath: config.outputPath,
      parameters,
      rowBounds: ir.rowBounds,
      scalarTypeImports: [...typeDependencies.scalar].toSorted(),
      sourceFile: config.sourceFile,
      sourcePath: config.sourcePath,
      sql: config.sql,
    })
  }

  return resolvedQueries
}

async function findStaleGeneratedFiles(
  configs: readonly ResolvedTypedSql[],
  generatorConfig: ResolvedPostgresTypedSqlConfig
): Promise<readonly string[]> {
  const expectedOutputPaths = new Set(
    await Promise.all(
      [generatorConfig.typesOutput, ...configs.map((config) => config.outputPath)].map(filesystemPathIdentity)
    )
  )
  const stale: string[] = []
  const generatedPaths = await findTypedSqlFiles(generatorConfig, [
    typedSqlOutputSuffix,
    ...legacyTypedSqlOutputSuffixes,
  ])
  for (const generatedPath of generatedPaths.toSorted()) {
    if (expectedOutputPaths.has(await filesystemPathIdentity(generatedPath))) {
      continue
    }

    const contents = await readFile(generatedPath, 'utf8')
    if (
      contents !== generatedMarkerLine &&
      !contents.startsWith(`${generatedMarkerLine}\n`) &&
      !contents.startsWith(`${generatedMarkerLine}\r\n`)
    ) {
      continue
    }

    stale.push(generatedPath)
  }
  return stale
}

interface GeneratedOutput {
  readonly contents: string
  readonly outputPath: string
}

interface StagedGeneratedOutput extends GeneratedOutput {
  readonly backupPath: string
  readonly existed: boolean
  readonly stagedPath: string
}

interface StagedGeneratedDeletion {
  readonly backupPath: string
  readonly outputPath: string
}

function isMissingFileError(error: unknown): boolean {
  return error instanceof Error && 'code' in error && error.code === 'ENOENT'
}

function isAlreadyExistsError(error: unknown): boolean {
  return error instanceof Error && 'code' in error && error.code === 'EEXIST'
}

async function existingContents(outputPath: string): Promise<string | null> {
  try {
    return await readFile(outputPath, 'utf8')
  } catch (error) {
    if (isMissingFileError(error)) {
      return null
    }
    throw error
  }
}

async function assertOutputIsNotSymbolicLink(outputPath: string): Promise<void> {
  try {
    const output = await lstat(outputPath)
    if (output.isSymbolicLink()) {
      throw new Error(`Generated output path ${outputPath} must not be a symbolic link.`)
    }
  } catch (error) {
    if (!isMissingFileError(error)) {
      throw error
    }
  }
}

async function canonicalFilesystemPath(path: string): Promise<string> {
  const missingSegments: string[] = []
  let existingAncestor = path

  while (true) {
    try {
      return join(await realpath(existingAncestor), ...missingSegments)
    } catch (error) {
      if (!isMissingFileError(error)) {
        throw error
      }
      const parent = dirname(existingAncestor)
      if (parent === existingAncestor) {
        throw error
      }
      missingSegments.unshift(basename(existingAncestor))
      existingAncestor = parent
    }
  }
}

async function filesystemPathIdentity(path: string): Promise<string> {
  return canonicalFilesystemPath(path)
}

async function cleanStagingFiles(
  staged: readonly StagedGeneratedOutput[],
  deletions: readonly StagedGeneratedDeletion[] = []
): Promise<void> {
  await Promise.allSettled(
    [
      ...staged.flatMap((entry) => [entry.stagedPath, entry.backupPath]),
      ...deletions.map((entry) => entry.backupPath),
    ].map((path) => rm(path, { force: true }))
  )
}

async function cleanStagedWrites(staged: readonly StagedGeneratedOutput[]): Promise<void> {
  await Promise.allSettled(staged.map((entry) => rm(entry.stagedPath, { force: true })))
}

async function rollbackGeneratedOutputs(
  installed: readonly StagedGeneratedOutput[],
  backedUp: readonly (StagedGeneratedDeletion | StagedGeneratedOutput)[]
): Promise<unknown[]> {
  const errors: unknown[] = []
  for (const entry of installed.toReversed()) {
    try {
      await rm(entry.outputPath, { force: true })
    } catch (error) {
      errors.push(error)
    }
  }
  for (const entry of backedUp.toReversed()) {
    try {
      await rename(entry.backupPath, entry.outputPath)
    } catch (error) {
      errors.push(error)
    }
  }
  return errors
}

async function commitGeneratedOutputs(
  outputs: readonly GeneratedOutput[],
  stalePaths: readonly string[]
): Promise<void> {
  const outputByPath = new Map<string, GeneratedOutput>()
  for (const output of outputs) {
    const identity = await filesystemPathIdentity(output.outputPath)
    const first = outputByPath.get(identity)
    if (first) {
      throw new Error(
        `Generated output paths ${first.outputPath} and ${output.outputPath} refer to the same filesystem destination, which is claimed more than once.`
      )
    }
    outputByPath.set(identity, output)
  }

  const orderedOutputs = [...outputByPath.values()].toSorted((left, right) =>
    left.outputPath.localeCompare(right.outputPath)
  )
  const staleByPath = new Map<string, string>()
  for (const stalePath of stalePaths) {
    const identity = await filesystemPathIdentity(stalePath)
    if (outputByPath.has(identity)) {
      throw new Error(`Generated output path ${stalePath} cannot be both installed and removed.`)
    }
    if (!staleByPath.has(identity)) {
      staleByPath.set(identity, stalePath)
    }
  }
  const orderedStalePaths = [...staleByPath.values()].toSorted()
  for (const output of orderedOutputs) {
    await assertOutputIsNotSymbolicLink(output.outputPath)
  }
  for (const stalePath of orderedStalePaths) {
    await assertOutputIsNotSymbolicLink(stalePath)
  }

  const staged: StagedGeneratedOutput[] = []
  const stagedByPath = new Map<string, StagedGeneratedOutput>()
  const batchNonce = `${process.pid}-${randomUUID()}`
  const deletions: StagedGeneratedDeletion[] = orderedStalePaths.map((outputPath) => ({
    backupPath: join(dirname(outputPath), `.${basename(outputPath)}.${process.pid}-${randomUUID()}.backup`),
    outputPath,
  }))
  try {
    for (const output of orderedOutputs) {
      const previous = await existingContents(output.outputPath)
      if (previous === output.contents) {
        continue
      }

      await mkdir(dirname(output.outputPath), { recursive: true })
      const stagedPath = join(dirname(output.outputPath), `.${basename(output.outputPath)}.${batchNonce}.staged`)
      const backupPath = join(dirname(output.outputPath), `.${basename(output.outputPath)}.${batchNonce}.backup`)
      try {
        await writeFile(stagedPath, output.contents, { flag: 'wx' })
      } catch (error) {
        if (isAlreadyExistsError(error)) {
          const first = stagedByPath.get(await filesystemPathIdentity(stagedPath))
          if (first) {
            throw new Error(
              `Generated output paths ${first.outputPath} and ${output.outputPath} refer to the same filesystem destination, which is claimed more than once.`
            )
          }
        }
        throw error
      }
      const entry = { ...output, backupPath, existed: previous !== null, stagedPath }
      staged.push(entry)
      stagedByPath.set(await filesystemPathIdentity(stagedPath), entry)
    }
  } catch (error) {
    await cleanStagingFiles(staged, deletions)
    throw error
  }

  const backedUp: (StagedGeneratedDeletion | StagedGeneratedOutput)[] = []
  const installed: StagedGeneratedOutput[] = []
  try {
    for (const entry of deletions) {
      await rename(entry.outputPath, entry.backupPath)
      backedUp.push(entry)
    }
    for (const entry of staged) {
      if (entry.existed) {
        await rename(entry.outputPath, entry.backupPath)
        backedUp.push(entry)
      }
    }
    for (const entry of staged) {
      await rename(entry.stagedPath, entry.outputPath)
      installed.push(entry)
    }
  } catch (error) {
    const rollbackErrors = await rollbackGeneratedOutputs(installed, backedUp)
    await cleanStagedWrites(staged)
    if (rollbackErrors.length > 0) {
      throw new AggregateError(
        [error, ...rollbackErrors],
        'Generated output commit failed and rollback was incomplete.'
      )
    }
    await cleanStagingFiles(staged, deletions)
    throw error
  }

  await cleanStagingFiles(staged, deletions)
}

export interface GenerateTypedSqlResult {
  readonly generatedFiles: readonly string[]
  readonly removedFiles: number
  readonly statementCount: number
  /** Present only when requested through the second argument. */
  readonly analysis?: TypedSqlGenerationAnalysis
}

export interface GenerateTypedSqlOptions {
  /** Return complete semantic facts and input provenance after outputs commit successfully. */
  readonly analysis?: boolean
}

export interface GenerateTypedSqlAnalysisResult extends GenerateTypedSqlResult {
  readonly analysis: TypedSqlGenerationAnalysis
}

export function generateTypedSql(
  config: PostgresTypedSqlConfig,
  options: GenerateTypedSqlOptions & { readonly analysis: true }
): Promise<GenerateTypedSqlAnalysisResult>
export function generateTypedSql(
  config: PostgresTypedSqlConfig,
  options?: GenerateTypedSqlOptions
): Promise<GenerateTypedSqlResult>
export async function generateTypedSql(
  config: PostgresTypedSqlConfig,
  options: GenerateTypedSqlOptions = {}
): Promise<GenerateTypedSqlResult> {
  if (generationInProgress) {
    throw new Error('Concurrent generation in one process is not supported.')
  }

  generationInProgress = true
  let database: Awaited<ReturnType<typeof createAnalysisDatabase>> | undefined

  try {
    const collectAnalysis = options.analysis === true
    const resolvedConfig = resolveConfig(config)
    // Do not retain caller-owned arrays across asynchronous work.
    const include = [...resolvedConfig.include]
    const extensions = [...resolvedConfig.extensions]
    const inputs: TypedSqlAnalysisInput[] = []
    const rawConfigs = await readTypedSqlConfigs(resolvedConfig)
    const configs = rawConfigs.map((config) => compileTypedSql(config, resolvedConfig.naming.parameterProperties))
    database = await createAnalysisDatabase({
      extensions,
      schemaFiles: resolvedConfig.schemaFiles,
      ...(collectAnalysis
        ? {
            readSchemaFile: async (path: string) => {
              const bytes = await readFile(path)
              inputs.push({ path, role: 'schema', sha256: sha256(bytes) })
              return bytes.toString('utf8')
            },
          }
        : {}),
    })
    const catalogContents = await buildCatalogTypes(database, resolvedConfig)
    const resolvedConfigs = await resolveTypedSqlWithAnalyzer(configs, database, resolvedConfig)

    const staleFiles = await findStaleGeneratedFiles(resolvedConfigs, resolvedConfig)
    const outputs = [
      { contents: catalogContents, outputPath: resolvedConfig.typesOutput },
      ...resolvedConfigs.map((entry) => ({
        contents: renderTypedSql(entry, resolvedConfig),
        outputPath: entry.outputPath,
      })),
    ]
    let analysis: TypedSqlGenerationAnalysis | undefined
    if (collectAnalysis) {
      inputs.push(
        ...rawConfigs.map((entry) => ({ path: entry.sourcePath, role: 'sql' as const, sha256: entry.sourceSha256 }))
      )
      const inputIdentities = new Set(await Promise.all(inputs.map((entry) => filesystemPathIdentity(entry.path))))
      for (const path of [...outputs.map((entry) => entry.outputPath), ...staleFiles]) {
        if (inputIdentities.has(await filesystemPathIdentity(path))) {
          throw new Error(`Generated output ${path} overlaps an analysis input.`)
        }
      }
      // Detect ordinary concurrent edits before committing. The hashes still describe
      // the consumed bytes if files change after this check; consumers must revalidate.
      for (const input of inputs) {
        if (sha256(await readFile(input.path)) !== input.sha256) {
          throw new Error(`Analysis input changed during generation: ${input.path}`)
        }
      }
      const discovered = (await findTypedSqlFiles(resolvedConfig, [typedSqlSourceSuffix])).toSorted()
      if (JSON.stringify(discovered) !== JSON.stringify(rawConfigs.map((entry) => entry.sourcePath).toSorted())) {
        throw new Error('SQL inventory changed during generation.')
      }
      const producer = JSON.parse(await readFile(new URL('../package.json', import.meta.url), 'utf8')) as {
        version: string
      }
      analysis = {
        version: generationAnalysisVersion,
        producer: { name: 'postgres-typed-sql', version: producer.version },
        postgresVersionNum: database.postgresVersionNum,
        rootDir: resolvedConfig.rootDir,
        include,
        extensions,
        inputs,
        statements: resolvedConfigs.map((entry) => ({
          source: entry.sourcePath,
          module: entry.outputPath,
          export: entry.name,
          sql: entry.sql,
          sqlSha256: sha256(entry.sql),
          access: entry.access,
          accessEvidence: entry.accessEvidence,
          parameters: entry.parameterAnalysis,
        })),
      }
    }
    await commitGeneratedOutputs(outputs, staleFiles)
    return {
      generatedFiles: resolvedConfigs.map((entry) => entry.outputPath),
      removedFiles: staleFiles.length,
      statementCount: configs.length,
      ...(analysis ? { analysis } : {}),
    }
  } finally {
    try {
      await database?.close()
    } finally {
      generationInProgress = false
    }
  }
}

export async function analyzeTypedSqlSource(input: {
  readonly sourcePath: string
  readonly content: string
  readonly database: AnalysisDatabase
  readonly config: ResolvedPostgresTypedSqlConfig
}): Promise<QueryAnalysis> {
  const parsed = parseTypedSqlConfig(input)
  const compiled = compileTypedSql(parsed, input.config.naming.parameterProperties)
  const [statement] = await resolveTypedSqlWithAnalyzer([compiled], input.database, input.config)
  if (!statement) throw new Error('PostgreSQL analyzer returned no statement.')
  return {
    source: input.sourcePath,
    sourceSha256: sha256(input.content),
    exports: { statement: statement.name, executor: 'default', types: statement.typeExports },
    sqlSha256: sha256(statement.sql),
    descriptor: queryDescriptor(statement),
    accessEvidence: statement.accessEvidence,
    parameters: statement.parameterAnalysis,
    moduleText: renderTypedSql(statement, input.config),
  }
}
