function quoteString(value: string): string {
  const escaped = value
    .replaceAll('\\', '\\\\')
    .replaceAll('\r', '\\r')
    .replaceAll('\n', '\\n')
    .replaceAll('\t', '\\t')
    .replaceAll('\u2028', '\\u2028')
    .replaceAll('\u2029', '\\u2029')

  return value.includes("'") ? `"${escaped.replaceAll('"', '\\"')}"` : `'${escaped.replaceAll("'", "\\'")}'`
}

